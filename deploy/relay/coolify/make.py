#!/usr/bin/env python3
"""Builds the Coolify package for the Sotto relay from a published, signed release.

    python3 deploy/relay/coolify/make.py v0.2.3

It downloads that release's latest.json and latest.json.sig from codewic/sotto-releases, checks
the signature against the release key pinned in this repository (with `sotto-release verify`),
takes the tools archive's SHA-256 from the signed manifest, and writes docker-compose.yml. The
image then installs exactly that archive's `sotto-relay` and refuses to build if a single byte
differs. Don't edit docker-compose.yml by hand; run this again for a new release.
"""

import json
import pathlib
import subprocess
import sys
import tempfile
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RELEASES = "https://github.com/codewic/sotto-releases/releases/download"
FETCH_IMAGE = "debian:bookworm-slim"
RUNTIME_IMAGE = "gcr.io/distroless/cc-debian12:nonroot"


def fetch(url, path):
    with urllib.request.urlopen(url, timeout=60) as r, open(path, "wb") as f:
        f.write(r.read())


def main():
    if len(sys.argv) != 2 or not sys.argv[1].startswith("v"):
        sys.exit("usage: make.py vX.Y.Z")
    tag = sys.argv[1]
    version = tag[1:]
    with tempfile.TemporaryDirectory() as tmp:
        manifest, sig = pathlib.Path(tmp) / "latest.json", pathlib.Path(tmp) / "latest.json.sig"
        fetch(f"{RELEASES}/{tag}/latest.json", manifest)
        fetch(f"{RELEASES}/{tag}/latest.json.sig", sig)
        ok = subprocess.run(["cargo", "run", "-q", "-p", "sotto-release", "--", "verify", str(manifest), str(sig)], cwd=ROOT)
        if ok.returncode != 0:
            sys.exit(f"{tag}'s manifest doesn't verify against the pinned release key; not packaging it")
        m = json.loads(manifest.read_text())
    if m.get("version") != version:
        sys.exit(f"the manifest is for {m.get('version')}, not {version}")
    name = f"sotto-tools-{version}-x86_64.tar.gz"
    entry = next((f for f in m["files"] if f["name"] == name), None)
    if not entry:
        sys.exit(f"{tag} has no {name}")
    sha = entry["sha256"]
    (HERE / "docker-compose.yml").write_text(compose(tag, name, sha))
    print(f"wrote deploy/relay/coolify/docker-compose.yml for {tag} ({name}, sha256 {sha[:16]}…)")


def compose(tag, name, sha):
    return f"""# Sotto relay for Coolify. Paste this whole file into Coolify: New Resource, Docker Compose
# Empty. Setup steps are in README.md next to this file. Generated by make.py for {tag};
# don't edit by hand.
#
# The image installs sotto-relay from the signed {tag} release: the archive's SHA-256 below
# comes from that release's manifest, whose signature make.py checked against the Sotto
# release key, and the build stops if the download doesn't match it.

services:
  relay:
    build:
      context: .
      dockerfile_inline: |
        FROM {FETCH_IMAGE} AS fetch
        RUN apt-get update && apt-get install -y --no-install-recommends curl ca-certificates && rm -rf /var/lib/apt/lists/*
        RUN curl -fsSL -o /tmp/tools.tar.gz {RELEASES}/{tag}/{name} \\
         && echo "{sha}  /tmp/tools.tar.gz" | sha256sum -c - \\
         && tar -xzf /tmp/tools.tar.gz -C /tmp sotto-relay \\
         && mkdir -p /data && chown 65532:65532 /data

        # Distroless: no shell, runs as a non-root user.
        FROM {RUNTIME_IMAGE}
        COPY --from=fetch /tmp/sotto-relay /usr/local/bin/sotto-relay
        COPY --from=fetch --chown=65532:65532 /data /data
        USER nonroot
        EXPOSE 7400
        ENTRYPOINT ["/usr/local/bin/sotto-relay", "--listen", "0.0.0.0:7400", "--data-dir", "/data", "--max-mb", "2048"]
    volumes:
      # Mailbox and group ids, their public keys and time limits, and sealed insurance packages.
      # Message content is held in memory only.
      - relay-data:/data
    read_only: true
    cap_drop:
      - ALL
    security_opt:
      - "no-new-privileges:true"
    restart: unless-stopped
    logging:
      driver: local
      options:
        max-size: "1m"
        max-file: "2"

volumes:
  relay-data:
"""


if __name__ == "__main__":
    main()
