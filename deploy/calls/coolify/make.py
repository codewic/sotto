#!/usr/bin/env python3
"""Builds the Coolify package for the Sotto call server from the real broker source.

    python3 deploy/calls/coolify/make.py          # regenerate docker-compose.yml and broker.Dockerfile
    python3 deploy/calls/coolify/make.py --lock   # also refresh broker.Cargo.lock (needs cargo)

The outputs are self-contained: the broker's Cargo.toml, Cargo.lock and source are written into
the Dockerfile as heredocs, so a Coolify server can build it without access to this repository.
Don't edit the outputs by hand; change the crate or this script and regenerate.
"""

import base64
import hashlib
import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CRATE = ROOT / "crates" / "sotto-call-broker"
LOCK = HERE / "broker.Cargo.lock"

LIVEKIT_IMAGE = "livekit/livekit-server:v1.13.3"
RUST_IMAGE = "rust:1.99.1-slim-trixie"
RUNTIME_IMAGE = "gcr.io/distroless/cc-debian13:nonroot"

# The standalone package: same dependencies as the crate, without test-only ones.
CARGO_TOML = """[package]
name = "sotto-call-broker"
version = "0.1.0"
edition = "2024"
license = "AGPL-3.0-or-later"
publish = false

[dependencies]
getrandom = "0.4.3"
livekit-token = "0.4.0"
livekit-protocol = "0.8.2"
axum = "0.8.9"
tokio = { version = "1.54.1", features = ["rt-multi-thread", "net", "macros", "time", "signal"] }
serde = { version = "1", features = ["derive"] }
serde_json = "1"

[profile.release]
lto = "thin"
codegen-units = 1
strip = true
panic = "abort"
"""

LIVEKIT_CONFIG = """port: 7880
rtc:
  tcp_port: 7881
  udp_port: 7882
  use_external_ip: true
turn:
  enabled: true
  udp_port: 3478
  relay_range_start: 30000
  relay_range_end: 30200
room:
  auto_create: true
  empty_timeout: 30
  departure_timeout: 20
  max_participants: 8
logging:
  level: warn
  pion_level: error
"""


def sources():
    return {
        "Cargo.toml": CARGO_TOML,
        "src/lib.rs": (CRATE / "src" / "lib.rs").read_text(),
        "src/main.rs": (CRATE / "src" / "main.rs").read_text(),
    }


def refresh_lock():
    """Resolve and build the standalone package once, keeping the Cargo.lock it produced."""
    with tempfile.TemporaryDirectory() as tmp:
        pkg = pathlib.Path(tmp) / "broker"
        for name, text in sources().items():
            path = pkg / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        subprocess.run(["cargo", "build", "--release", "-j", "2"], cwd=pkg, check=True)
        shutil.copy(pkg / "Cargo.lock", LOCK)
        print(f"wrote {LOCK.relative_to(ROOT)}")


def dockerfile():
    files = sources()
    if not LOCK.exists():
        sys.exit("broker.Cargo.lock is missing: run with --lock first")
    files["Cargo.lock"] = LOCK.read_text()
    out = [
        "# Sotto call broker, built from the source embedded below (base64, so every Docker",
        "# builder accepts it and Compose finds nothing to substitute). Generated by",
        "# deploy/calls/coolify/make.py from crates/sotto-call-broker; don't edit by hand.",
        f"FROM {RUST_IMAGE} AS build",
        "WORKDIR /src",
        "RUN mkdir -p /src/src",
    ]
    for name, text in files.items():
        b64 = base64.b64encode(text.encode()).decode()
        out.append(f"# {name} ({len(text.encode())} bytes, sha256 {hashlib.sha256(text.encode()).hexdigest()})")
        out.append(f"RUN echo '{b64}' | base64 -d > /src/{name}")
    out += [
        "RUN cargo build --release --locked",
        "",
        "# Distroless: no shell, runs as a non-root user.",
        f"FROM {RUNTIME_IMAGE}",
        "COPY --from=build /src/target/release/sotto-call-broker /usr/local/bin/sotto-call-broker",
        "USER nonroot",
        "EXPOSE 7890",
        'ENTRYPOINT ["/usr/local/bin/sotto-call-broker"]',
    ]
    text = "\n".join(out) + "\n"
    if "$" in text:
        sys.exit("the broker source contains '$', which Docker Compose would try to substitute")
    return text


def indent(text, n):
    pad = " " * n
    return "\n".join(pad + line if line else "" for line in text.splitlines())


def compose(df):
    return f"""# Sotto call server for Coolify: LiveKit (calls) and the Sotto call broker (join tokens).
# Paste this whole file into Coolify: New Resource, Docker Compose Empty. Setup steps are in
# README.md next to this file. Generated by make.py; don't edit by hand.
#
# Coolify fills in SERVICE_USER_LIVEKIT and SERVICE_PASSWORD_64_LIVEKIT with random values.
# You set LIVEKIT_PUBLIC_URL in Coolify's Environment Variables (the LiveKit domain).

services:
  livekit:
    image: {LIVEKIT_IMAGE}
    environment:
      LIVEKIT_KEYS: "${{SERVICE_USER_LIVEKIT}}: ${{SERVICE_PASSWORD_64_LIVEKIT}}"
      LIVEKIT_CONFIG: |
{indent(LIVEKIT_CONFIG, 8)}
    ports:
      # Media. Signalling (7880) goes through Coolify's proxy on the LiveKit domain instead.
      - "7881:7881/tcp"
      - "7882:7882/udp"
      - "3478:3478/udp"
      - "30000-30200:30000-30200/udp"
    restart: unless-stopped
    logging:
      driver: local
      options:
        max-size: "1m"
        max-file: "2"

  broker:
    build:
      context: .
      dockerfile_inline: |
{indent(df, 8)}
    environment:
      SOTTO_CALLS_URL: "${{LIVEKIT_PUBLIC_URL}}"
      LIVEKIT_API_KEY: "${{SERVICE_USER_LIVEKIT}}"
      LIVEKIT_API_SECRET: "${{SERVICE_PASSWORD_64_LIVEKIT}}"
      BROKER_BIND: "0.0.0.0:7890"
      # Coolify's proxy runs in its own container, so trust its X-Forwarded-For.
      BROKER_TRUST_PRIVATE_PROXY: "true"
      BROKER_RATE_GLOBAL_PER_MIN: "120"
      BROKER_RATE_IP_PER_MIN: "20"
    read_only: true
    cap_drop:
      - ALL
    security_opt:
      - "no-new-privileges:true"
    restart: unless-stopped
    logging:
      driver: local
      options:
        max-size: "1m"
        max-file: "2"
"""


def main():
    if "--lock" in sys.argv:
        refresh_lock()
    df = dockerfile()
    (HERE / "broker.Dockerfile").write_text(df)
    (HERE / "docker-compose.yml").write_text(compose(df))
    print("wrote deploy/calls/coolify/broker.Dockerfile and docker-compose.yml")


if __name__ == "__main__":
    main()
